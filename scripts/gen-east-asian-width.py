#!/usr/bin/env python3
"""Generate src/Creole/Errors/EastAsianWidth.g.cs from the Unicode Character Database.

The diagnostic renderer counts a character as two terminal columns when its East_Asian_Width is
Wide (W) or Fullwidth (F). .NET has no API for that property, so Creole carries the table.

Use the Unicode version the pinned .NET runtime uses, so widths agree with StringInfo's grapheme
clusters. .NET 11 uses 16.0.0 (dotnet/runtime-assets, System.Private.Runtime.UnicodeData).

    python3 scripts/gen-east-asian-width.py                    # downloads 16.0.0
    python3 scripts/gen-east-asian-width.py --version 17.0.0
    python3 scripts/gen-east-asian-width.py --input EastAsianWidth.txt --version 16.0.0
"""

import argparse
import os
import sys
import urllib.request

OUTPUT = os.path.join(os.path.dirname(__file__), "..", "src", "Creole", "Errors", "EastAsianWidth.g.cs")

# Unlisted code points default to N, except these blocks, which default to W (header of EastAsianWidth.txt).
DEFAULT_WIDE = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]


def read_source(args):
    if args.input:
        with open(args.input, encoding="utf-8") as f:
            return f.read()
    url = f"https://www.unicode.org/Public/{args.version}/ucd/EastAsianWidth.txt"
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def wide_ranges(text, version):
    first = text.splitlines()[0]
    if version not in first:
        sys.exit(f"Expected EastAsianWidth-{version}.txt, but the file starts with: {first}")

    wide = bytearray(0x110000)
    for start, end in DEFAULT_WIDE:
        wide[start:end + 1] = b"\x01" * (end - start + 1)

    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        codes, value = (part.strip() for part in data.split(";"))
        start, _, end = codes.partition("..")
        start = int(start, 16)
        end = int(end, 16) if end else start
        flag = b"\x01" if value in ("W", "F") else b"\x00"
        wide[start:end + 1] = flag * (end - start + 1)

    ranges = []
    cp = 0
    while cp < len(wide):
        if wide[cp]:
            start = cp
            while cp + 1 < len(wide) and wide[cp + 1]:
                cp += 1
            ranges.append((start, cp))
        cp += 1
    return ranges


def render(ranges, version):
    rows = []
    for i in range(0, len(ranges), 4):
        row = ", ".join(f"0x{s:04X}, 0x{e:04X}" for s, e in ranges[i:i + 4])
        rows.append(f"        {row},")
    body = "\n".join(rows)
    return f"""// <auto-generated>
// Generated by scripts/gen-east-asian-width.py from Unicode {version} EastAsianWidth.txt. Do not edit by hand.
// </auto-generated>

namespace Creole;

/// <summary>
/// The code points whose East_Asian_Width is Wide (W) or Fullwidth (F), which terminals show two columns wide.
/// </summary>
internal static class EastAsianWidth
{{
    /// <summary>
    /// The Unicode version the table was generated from.
    /// </summary>
    public const string UnicodeVersion = "{version}";

    // Inclusive ranges as pairs of first and last code point, in ascending order.
    private static ReadOnlySpan<int> WideRanges =>
    [
{body}
    ];

    /// <summary>
    /// Returns whether <paramref name="codePoint"/> is Wide or Fullwidth.
    /// </summary>
    public static bool IsWide(int codePoint)
    {{
        var ranges = WideRanges;
        var low = 0;
        var high = ranges.Length / 2 - 1;

        while (low <= high)
        {{
            var mid = (low + high) / 2;

            if (codePoint < ranges[2 * mid])
            {{
                high = mid - 1;
            }}
            else if (codePoint > ranges[2 * mid + 1])
            {{
                low = mid + 1;
            }}
            else
            {{
                return true;
            }}
        }}

        return false;
    }}
}}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", default="16.0.0", help="Unicode version (default 16.0.0)")
    parser.add_argument("--input", help="a local EastAsianWidth.txt instead of downloading it")
    args = parser.parse_args()

    ranges = wide_ranges(read_source(args), args.version)
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(ranges, args.version))
    print(f"Wrote {len(ranges)} ranges to {os.path.normpath(OUTPUT)}")


if __name__ == "__main__":
    main()
